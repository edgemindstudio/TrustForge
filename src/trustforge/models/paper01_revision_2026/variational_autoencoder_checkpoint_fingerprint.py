"""Candidate paired-VAE architecture fingerprint contract.

Paper 1 revision 2026.

Captures Keras model configurations and ordered variable
specifications. Does not authenticate checkpoint history,
guarantee cross-version portability, or authorize restoration.
"""

from __future__ import annotations

import copy
import hashlib
import json
import re

from trustforge.models.paper01_revision_2026.variational_autoencoder_checkpoint_state import (
    ROLE_ENCODER,
    ROLE_DECODER,
    variable_specification,
)


FINGERPRINT_SCHEMA_VERSION = "candidate_v1"


def _canonical_json_bytes(value):
    """Serialize a JSON-compatible descriptor deterministically."""
    return json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
        allow_nan=False,
    ).encode("utf-8")


def _canonicalize_encoder_configuration(configuration):
    """Normalize only the two governed autogenerated encoder names.

    Preserve all other layer configuration and graph connections.
    Unexpected or ambiguous layer naming is rejected.
    """
    result = copy.deepcopy(configuration)
    layers = result["layers"]

    names = [layer["name"] for layer in layers]

    if len(names) != len(set(names)):
        raise ValueError("duplicate encoder layer names")

    mapping = {}

    for canonical, expected_class in (
        ("repeat_vector", "RepeatVector"),
        ("reshape", "Reshape"),
    ):
        pattern = re.compile(
            re.escape(canonical) + r"(?:_[1-9][0-9]*)?"
        )

        matches = [
            layer
            for layer in layers
            if pattern.fullmatch(layer["name"]) is not None
        ]

        if len(matches) != 1:
            raise ValueError(
                f"ambiguous encoder layer: {canonical}"
            )

        layer = matches[0]

        if (
            layer["class_name"] != expected_class
            or layer["config"]["name"] != layer["name"]
        ):
            raise ValueError(
                f"unexpected encoder layer: {canonical}"
            )

        mapping[layer["name"]] = canonical

    canonical_names = set(mapping.values())

    for name in names:
        if name not in mapping and name in canonical_names:
            raise ValueError(
                "canonical encoder layer name collision"
            )

    for layer in layers:
        old_name = layer["name"]

        if old_name in mapping:
            canonical = mapping[old_name]
            layer["name"] = canonical
            layer["config"]["name"] = canonical

    def rewrite_graph_references(value):
        if isinstance(value, dict):
            if value.get("class_name") == "__keras_tensor__":
                config = value.get("config")

                if not isinstance(config, dict):
                    raise ValueError("invalid Keras tensor config")

                history = config.get("keras_history")

                if (
                    not isinstance(history, list)
                    or len(history) != 3
                ):
                    raise ValueError("invalid Keras tensor history")

                if history[0] in mapping:
                    history[0] = mapping[history[0]]

            for nested in value.values():
                rewrite_graph_references(nested)

        elif isinstance(value, (list, tuple)):
            for nested in value:
                rewrite_graph_references(nested)

    rewrite_graph_references(result)

    final_names = [layer["name"] for layer in layers]

    if len(final_names) != len(set(final_names)):
        raise ValueError("canonical encoder name collision")

    return result


def _network_descriptor(network, *, role):
    """Capture a network's serialized graph and variable inventory."""
    specification = variable_specification(
        network,
        role=role,
    )

    return {
        "keras_configuration": (
            _canonicalize_encoder_configuration(
                network.get_config()
            )
            if role == ROLE_ENCODER
            else network.get_config()
        ),
        "variable_specification": [
            {
                "key": entry["key"],
                "shape": list(entry["shape"]),
                "dtype": entry["dtype"],
                "trainable": entry["trainable"],
            }
            for entry in specification
        ],
    }


def describe_vae_architecture(
    *,
    encoder,
    decoder,
    class_count,
    latent_dim=100,
):
    """Produce a deterministic candidate architecture descriptor."""
    if type(class_count) is not int or class_count < 1:
        raise ValueError("invalid architecture class count")

    if type(latent_dim) is not int or latent_dim != 100:
        raise ValueError("unsupported architecture latent dimension")

    descriptor = {
        "fingerprint_schema_version": FINGERPRINT_SCHEMA_VERSION,
        "class_count": class_count,
        "latent_dim": latent_dim,
        "encoder": _network_descriptor(
            encoder,
            role=ROLE_ENCODER,
        ),
        "decoder": _network_descriptor(
            decoder,
            role=ROLE_DECODER,
        ),
    }

    _canonical_json_bytes(descriptor)

    return descriptor


def fingerprint_vae_architecture(
    *,
    encoder,
    decoder,
    class_count,
    latent_dim=100,
):
    """Return the SHA-256 digest of the paired architecture descriptor."""
    descriptor = describe_vae_architecture(
        encoder=encoder,
        decoder=decoder,
        class_count=class_count,
        latent_dim=latent_dim,
    )

    return hashlib.sha256(
        _canonical_json_bytes(descriptor)
    ).hexdigest()


__all__ = [
    "FINGERPRINT_SCHEMA_VERSION",
    "describe_vae_architecture",
    "fingerprint_vae_architecture",
]
